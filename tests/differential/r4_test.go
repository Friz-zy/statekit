func TestR4DifferentialReport(t *testing.T) {
	rt, err := bootstrap.BuildRuntime()
	if err != nil {
		t.Fatal(err)
	}
	registered := registeredNames(rt)

	report := roundReport{Round: "R4", Families: map[string]familyReport{}}
	for _, family := range r4Families {
		catalogNames := loadCatalogFunctionNames(t, family)
		fam := familyReport{
			Catalog:   len(catalogNames),
			Scenarios: r4ScenarioManifest[family],
		}
		for _, name := range catalogNames {
			if strings.HasPrefix(name, "_") {
				fam.Private++
				continue
			}
			fam.Public++
			full := family + "." + name
			if registered[full] {
				fam.Registered++
				continue
			}
			// Salt's keyword-escape convention: a trailing underscore in the
			// catalog name resolves through __func_alias__ to the stripped
			// CLI-facing name (set_ -> set).
			alias := strings.TrimSuffix(name, "_")
			if alias != name && registered[family+"."+alias] {
				fam.Registered++
				continue
			}
			fam.PendingPublic = append(fam.PendingPublic, full)
		}
		report.Totals.Catalog += fam.Catalog
		report.Totals.Public += fam.Public
		report.Totals.Registred += fam.Registered
		report.Families[family] = fam
	}

	encoded, err := yaml.Marshal(report)
	if err != nil {
		t.Fatal(err)
	}
	outPath := filepath.Join("..", "..", "docs", "differential", "R4", "report.yaml")
	want := "# Generated by tests/differential (TestR4DifferentialReport); do not edit.\n" + string(encoded)

	existing, rerr := os.ReadFile(outPath)
	if rerr == nil && string(existing) == want {
		return
	}
	if os.Getenv("UPDATE_DIFFERENTIAL") == "1" {
		if mkerr := os.MkdirAll(filepath.Dir(outPath), 0o755); mkerr != nil {
			t.Fatal(mkerr)
		}
		if werr := os.WriteFile(outPath, []byte(want), 0o644); werr != nil {
			t.Fatal(werr)
		}
		return
	}
	t.Fatalf("differential report stale; run UPDATE_DIFFERENTIAL=1 go test ./tests/differential\n--- want ---\n%s", want)
}
