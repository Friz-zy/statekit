type staticDelegate struct {
	name string
	res  any
}

func (d *staticDelegate) Name() string { return d.name }
func (d *staticDelegate) Args() any    { return struct{}{} }
func (d *staticDelegate) Execute(_ context.Context, _ *runtime.Runtime, _ any) (any, error) {
	return d.res, nil
}

type writeCapture struct{ content string }

func (w *writeCapture) Name() string { return "file.write" }
func (w *writeCapture) Args() any    { return struct{}{} }
func (w *writeCapture) Execute(_ context.Context, _ *runtime.Runtime, args any) (any, error) {
	switch t := args.(type) {
	case map[string]string:
		w.content = t["Content"]
	case *struct {
		Path    string
		Content string
	}:
		w.content = t.Content
	}
	return true, nil
}

