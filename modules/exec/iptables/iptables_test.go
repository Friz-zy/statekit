func strPtr(s string) *string { return &s }

func boolPtr(b bool) *bool { return &b }

func kw(pairs ...any) map[string]any {
	m := map[string]any{}
	for i := 0; i+1 < len(pairs); i += 2 {
		m[pairs[i].(string)] = pairs[i+1]
	}
	return m
}

// Mirrors the build_rule fixture battery from test_build_rule.
func TestBuildRuleFixtures(t *testing.T) {
	bindPath(t, "/sbin/iptables")
	rt := newRT(t, nil, "Debian")
	savedHas := hasOptionFn
	hasOptionFn = func(context.Context, *runtime.Runtime, string, string) bool { return true }
	t.Cleanup(func() { hasOptionFn = savedHas })

	brf := buildRuleFunc{}
	exec := func(args *BuildRuleArgs) string {
		gotRaw, err := brf.Execute(context.Background(), rt, args)
		if err != nil {
			t.Fatal(err)
		}
		return gotRaw.(string)
	}

	if got := exec(&BuildRuleArgs{}); got != "" {
		t.Fatalf("empty rule = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("name", "ignored", "state", "ignored")}); got != "" {
		t.Fatalf("name/state ignored, got %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("if", "!eth0")}); got != "! -i eth0" {
		t.Fatalf("bang negation = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("if", "not eth0")}); got != "! -i eth0" {
		t.Fatalf("not negation = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("protocol", "tcp", "syn", "!")}); got != "-p tcp ! --syn" {
		t.Fatalf("negated flag value = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("dports", []any{int64(80), int64(443)}, "protocol", "tcp")}); got != "-p tcp -m multiport --dports 80,443" {
		t.Fatalf("dports list = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("dports", "80,443", "protocol", "tcp")}); got != "-p tcp -m multiport --dports 80,443" {
		t.Fatalf("dports string = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("dports", []any{"!80", int64(443)}, "protocol", "tcp")}); got != "-p tcp -m multiport ! --dports 80,443" {
		t.Fatalf("dports list negation = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("dports", "!80,443", "protocol", "tcp")}); got != "-p tcp -m multiport ! --dports 80,443" {
		t.Fatalf("dports string negation = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("sports", []any{int64(80), int64(443)}, "protocol", "tcp")}); got != "-p tcp -m multiport --sports 80,443" {
		t.Fatalf("sports = %q", got)
	}
	for _, bad := range []string{"dports", "sports"} {
		m := map[string]any{bad: "protocol", "jump": "ACCEPT"}
		got := exec(&BuildRuleArgs{
			Table: strPtr("filter"), Chain: strPtr("INPUT"),
			Command: strPtr("I"), Full: boolPtr(true), Kwargs: m,
		})
		if got != "Error: protocol must be specified" {
			t.Fatalf("%s without protocol = %q", bad, got)
		}
	}
	if got := exec(&BuildRuleArgs{
		Table:   strPtr(""),
		Chain:   strPtr("INPUT"),
		Command: strPtr("I"),
		Full:    boolPtr(true),
		Kwargs:  kw("match", "state", "jump", "ACCEPT"),
	}); got != "Error: Table needs to be specified" {
		t.Fatalf("table error = %q", got)
	}
	if got := exec(&BuildRuleArgs{
		Table: strPtr("filter"), Command: strPtr("I"), Full: boolPtr(true),
		Kwargs: kw("match", "state", "jump", "ACCEPT"),
	}); got != "Error: Chain needs to be specified" {
		t.Fatalf("chain error = %q", got)
	}
	if got := exec(&BuildRuleArgs{
		Table: strPtr("filter"), Chain: strPtr("INPUT"), Full: boolPtr(true),
		Kwargs: kw("match", "state", "jump", "ACCEPT"),
	}); got != "Error: Command needs to be specified" {
		t.Fatalf("command error = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("jump", "REDIRECT", "to-port", int64(8080))}); got != "--jump REDIRECT --to-port 8080" {
		t.Fatalf("after-jump ordering = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("jump", "LOG", "log-prefix", "long prefix")}); got != `--jump LOG --log-prefix "long prefix"` {
		t.Fatalf("quoted log-prefix = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("jump", "LOG", "log-prefix", "spam: ")}); got != `--jump LOG --log-prefix "spam: "` {
		t.Fatalf("trailing-space quote = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("jump", "CLUSTERIP", "new", "")}); got != "--jump CLUSTERIP --new" {
		t.Fatalf("no-arg jump option = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("jump", "CT", "notrack", nil)}); got != "--jump CT --notrack" {
		t.Fatalf("None no-arg option = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("match-set", "src flag1,flag2")}); got != "-m set --match-set src flag1,flag2" {
		t.Fatalf("single match-set = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("match-set", []any{"src1 flag1", "src2 flag2,flag3"})}); got != "-m set --match-set src1 flag1 -m set --match-set src2 flag2,flag3" {
		t.Fatalf("list match-sets = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("match-set", "!src flag")}); got != "-m set ! --match-set src flag" {
		t.Fatalf("negated match-set = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("match-set", []any{"src1 flag", "not src2 flag2"})}); got != "-m set --match-set src1 flag -m set ! --match-set src2 flag2" {
		t.Fatalf("negated match-set list = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("match", "recent", "name_", "SSH")}); got != "-m recent --name SSH" {
		t.Fatalf("recent name_ = %q", got)
	}
	if got := exec(&BuildRuleArgs{Kwargs: kw("match", "recent", "update", nil)}); got != "-m recent --update" {
		t.Fatalf("empty argument = %q", got)
	}

	want := "/sbin/iptables --wait -t salt -I INPUT 3 -m state --jump ACCEPT"
	got := exec(&BuildRuleArgs{
		Table:    strPtr("salt"),
		Chain:    strPtr("INPUT"),
		Command:  strPtr("I"),
		Position: "3",
		Full:     boolPtr(true),
		Kwargs:   kw("match", "state", "jump", "ACCEPT"),
	})
	if got != want {
		t.Fatalf("full command = %q, want %q", got, want)
	}
}

// Mirrors test_get_saved_rules_nilinuxrt: the NILinuxRT conf parses into
// the documented rules structure.
func TestGetSavedRulesParse(t *testing.T) {
	bindPath(t, "/usr/sbin/iptables")
	rt := newRT(t, nil, "NILinuxRT")
	if err := rt.FS.MkdirAll("/etc/natinst/share", 0o755); err != nil {
		t.Fatal(err)
	}
	if err := rt.FS.WriteFile("/etc/natinst/share/iptables.conf", []byte(confFixture), 0o644); err != nil {
		t.Fatal(err)
	}

	gotRaw, err := getSavedRulesFunc{}.Execute(context.Background(), rt, &GetSavedRulesArgs{})
	if err != nil {
		t.Fatal(err)
	}
	rules := gotRaw.(map[string]any)
	filter, ok := rules["filter"].(map[string]any)
	if !ok {
		t.Fatalf("filter table missing: %#v", rules)
	}
	input := filter["INPUT"].(map[string]any)
	if input["policy"] != "ACCEPT" || input["packet count"] != "2958" ||
		input["byte count"] != "584773" {
		t.Fatalf("INPUT header = %#v", input)
	}
	wantRules := []any{
		map[string]any{
			"protocol":         []any{"tcp"},
			"jump":             []any{"ACCEPT"},
			"match":            []any{"tcp"},
			"destination_port": []any{"80"},
		},
	}
	if !reflect.DeepEqual(input["rules"], wantRules) {
		t.Fatalf("parsed rules = %#v, want %#v", input["rules"], wantRules)
	}
}

