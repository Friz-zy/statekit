func newRT(t *testing.T, runner *fakeRunner, osFamily string) *runtime.Runtime {
	t.Helper()
	rt := &runtime.Runtime{
		Exec:   runtime.NewExecRegistry(),
		States: runtime.NewStateRegistry(),
		FS:     runtime.NewMemoryFS(),
	}
	if runner != nil {
		rt.Runner = runner
	} else {
		rt.Runner = &fakeRunner{}
	}
	if err := execcmd.Register(rt.Exec); err != nil {
		t.Fatal(err)
	}
	if err := Register(rt.Exec); err != nil {
		t.Fatal(err)
	}

	savedFamily, savedOS := osFamilyHook, osHook
	osFamilyHook = func(*runtime.Runtime) string { return osFamily }
	osHook = func(*runtime.Runtime) string { return osFamily }
	t.Cleanup(func() { osFamilyHook, osHook = savedFamily, savedOS })

	savedNode := getNodeHex
	getNodeHex = func() string { return "0x7a69" }
	t.Cleanup(func() { getNodeHex = savedNode })
	return rt
}

func bindPath(t *testing.T, path string) {
	t.Helper()
	saved := iptablesPath
	iptablesPath = func(string) string { return path }
	t.Cleanup(func() { iptablesPath = saved })
}

