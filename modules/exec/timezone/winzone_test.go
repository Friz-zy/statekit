// WZC-01/WZC-06 (GAP-03/06): the requested-name gate runs strictly
// before any resolver API call, before the Lstat precheck, and before
// any dispatch — missing, empty, untrimmed, and unlisted names each
// return only the fixed ErrInvalidWindowsZone with zero work, while a
// mixed-case listed name (never trimmed) proceeds to exactly one
// dispatch.
func TestWinZoneCompareGateBeforeResolverAndPrecheck(t *testing.T) {
	for _, tc := range []struct {
		label string
		zone  string
	}{
		{"explicit empty", ""},
		{"unlisted nonempty", "Indian Standard Time"},
		{"trailing space never trimmed", "Mountain Standard Time "},
		{"leading space never trimmed", " Mountain Standard Time"},
		{"trailing newline never trimmed", "UTC\n"},
		{"interior double space", "Mountain  Standard Time"},
	} {
		env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("Mountain Standard Time\r\n")}, nil)
		_, err := winZoneCompareExec(t, env, tc.zone)
		requireWinZoneInvalid(t, err)
		if tc.zone != "" && strings.Contains(err.Error(), tc.zone) {
			t.Fatalf("%s: error text %q leaks the requested name", tc.label, err.Error())
		}
		if env.resolver.calls != 0 {
			t.Fatalf("%s: resolver called %d times, want 0", tc.label, env.resolver.calls)
		}
		if len(env.runner.cmds) != 0 {
			t.Fatalf("%s: dispatched %d commands, want 0", tc.label, len(env.runner.cmds))
		}
		if len(env.fsys.calls) != 0 {
			t.Fatalf("%s: touched the filesystem: %v", tc.label, env.fsys.calls)
		}
	}

	// Contrast: a mixed-case listed name dispatches exactly once and
	// compares case-insensitively (WZC-02).
	env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("India Standard Time\r\n")}, nil)
	value, err := winZoneCompareExec(t, env, "iNdIa standard TIME")
	if err != nil || value != true {
		t.Fatalf("mixed-case request = %v, %v; want true, nil", value, err)
	}
	if len(env.runner.cmds) != 1 {
		t.Fatalf("mixed-case request dispatched %d commands, want 1", len(env.runner.cmds))
	}

	// Wrong argument type and typed-nil argument fail safe with the
	// invalid-zone sentinel and zero work.
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("UTC\r\n")}, nil)
	for _, args := range []any{"Secret/Zone", (*winZoneCompareArgs)(nil), zoneCompareArgs{TimeZone: "UTC"}, nil} {
		_, err = (winZoneCompareFunc{}).Execute(context.Background(), env.rt, args)
		requireWinZoneInvalid(t, err)
		if strings.Contains(err.Error(), "Secret") || strings.Contains(err.Error(), "UTC") {
			t.Fatalf("malformed args error text %q leaks argument material", err.Error())
		}
	}
	if env.resolver.calls != 0 || len(env.runner.cmds) != 0 || len(env.fsys.calls) != 0 {
		t.Fatalf("malformed args did work: resolver=%d dispatch=%d fs=%v", env.resolver.calls, len(env.runner.cmds), env.fsys.calls)
	}
}

// WZC-11/WZC-10 (dispatch shape): exactly one shell-free
// <systemdir>\tzutil.exe /g with Dir=systemdir, Env exactly the two
// API-derived SYSTEMROOT/WINDIR entries, a 30s cancellation deadline,
// and 64 KiB per-stream ceilings; no user input travels in argv or
// env, and hostile PATHEXT siblings never redirect the exact name
// while the exact executable is present.
func TestWinZoneCompareDispatchShape(t *testing.T) {
	env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("Mountain Standard Time_dstoff\r\n")}, func(mem runtime.FileSystem, _ *zoneRecordingFS) {
		zoneMustWrite(mem, winZoneTestExe, []byte("MZ fake tzutil"))
		zoneMustWrite(mem, winZoneTestSysdir+`\tzutil.exe.com`, []byte("hijack"))
		zoneMustWrite(mem, winZoneTestSysdir+`\tzutil.exe.cmd`, []byte("hijack"))
	})
	value, err := winZoneCompareExec(t, env, "America/Denver")
	if err != nil || value != true {
		t.Fatalf("dstoff compare = %v, %v; want true, nil", value, err)
	}
	if len(env.runner.cmds) != 1 {
		t.Fatalf("dispatched %d commands, want exactly 1", len(env.runner.cmds))
	}
	want := process.Command{
		Name:           winZoneTestExe,
		Args:           []string{"/g"},
		Dir:            winZoneTestSysdir,
		Env:            []string{"SYSTEMROOT=" + winZoneTestWindir, "WINDIR=" + winZoneTestWindir},
		Timeout:        30 * time.Second,
		MaxStdoutBytes: 64 << 10,
		MaxStderrBytes: 64 << 10,
	}
	got := env.runner.cmds[0]
	if got.Name != want.Name || !reflect.DeepEqual(got.Args, want.Args) || got.Dir != want.Dir ||
		!reflect.DeepEqual(got.Env, want.Env) || got.Shell || got.WindowsCmdLine != "" ||
		got.Timeout != want.Timeout || got.MaxStdoutBytes != want.MaxStdoutBytes ||
		got.MaxStderrBytes != want.MaxStderrBytes || len(got.Stdin) != 0 || len(got.Redact) != 0 {
		t.Fatalf("command =\n%+v\nwant\n%+v", got, want)
	}
	requireZoneReadOnly(t, env.fsys)
}

// WZC-09/WZC-10 (precheck boundary): an exact Lstat of the executable
// runs immediately before dispatch and requires a regular non-reparse
// answer; a missing, reparse, or non-regular executable answers the
// fixed ErrCannotDetermineZone with zero dispatch and no PATHEXT
// suffix fallback. The precheck cannot close the TOCTOU window between
// Lstat and process start — the admin-controlled system-tree
// assumption carries that residual, documented in the plan record.
func TestWinZoneComparePrecheckBoundary(t *testing.T) {
	seed := func(mem runtime.FileSystem) { zoneMustWrite(mem, winZoneTestExe, []byte("MZ fake tzutil")) }
	cases := []struct {
		label string
		mode  fs.FileMode
	}{
		{"missing exe", 0}, // no node: Lstat errors naturally
		{"reparse symlink exe", fs.ModeSymlink | 0o777},
		{"directory exe", fs.ModeDir | 0o755},
	}
	for _, tc := range cases {
		env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("UTC\r\n")}, func(mem runtime.FileSystem, rec *zoneRecordingFS) {
			if tc.mode != 0 {
				seed(mem)
				rec.lstatMode[winZoneTestExe] = tc.mode
			}
		})
		_, err := winZoneCompareExec(t, env, "UTC")
		requireWinZoneCannotDetermine(t, err)
		if len(env.runner.cmds) != 0 {
			t.Fatalf("%s: dispatched %d commands, want 0", tc.label, len(env.runner.cmds))
		}
		requireZoneCalls(t, env.fsys, []string{"lstat:" + winZoneTestExe})
	}

	// WZC-10: exact file missing while PATHEXT-appended siblings exist
	// — the precheck must fail closed rather than let the Runner fall
	// back to tzutil.exe.com/.cmd.
	env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("UTC\r\n")}, func(mem runtime.FileSystem, _ *zoneRecordingFS) {
		zoneMustWrite(mem, winZoneTestSysdir+`\tzutil.exe.com`, []byte("hijack"))
		zoneMustWrite(mem, winZoneTestSysdir+`\tzutil.exe.cmd`, []byte("hijack"))
	})
	_, err := winZoneCompareExec(t, env, "UTC")
	requireWinZoneCannotDetermine(t, err)
	if len(env.runner.cmds) != 0 {
		t.Fatalf("hostile PATHEXT: dispatched %d commands, want 0", len(env.runner.cmds))
	}
}

