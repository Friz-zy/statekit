// WZC-05 (GAP-01/02): Python str.rstrip whitespace semantics on the
// captured stdout (CRLF, tab, U+00A0, U+0085, U+2028, U+3000,
// U+001C..U+001F), leading whitespace preserved (and therefore simply
// unmatched), empty-after-rstrip failing closed, lowercasing, and the
// exactly-one terminal _dstoff strip including the repeated suffix.
func TestWinZoneCompareOutputMatrix(t *testing.T) {
	trailing := []string{
		"\r\n", "\n", "\r", "\t", " ", "\v", "\f", "\u0085", "\u00A0",
		"\u2028", "\u2029", "\u3000", "\u001C", "\u001D", "\u001E", "\u001F",
		"\r\n\t \u00A0\u3000",
	}
	for _, suffix := range trailing {
		env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("UTC" + suffix)}, nil)
		value, err := winZoneCompareExec(t, env, "UTC")
		if err != nil || value != true {
			t.Fatalf("trailing %q: = %v, %v; want true, nil", suffix, value, err)
		}
	}

	// Leading whitespace is preserved, so the name simply does not
	// match — false, not an error.
	env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("  UTC\r\n")}, nil)
	value, err := winZoneCompareExec(t, env, "UTC")
	if err != nil || value != false {
		t.Fatalf("leading whitespace = %v, %v; want false, nil", value, err)
	}

	// Empty-after-rstrip (empty or whitespace-only stdout) fails closed.
	for _, stdout := range []string{"", " ", "\r\n", " \t\r\n\u001F", "\u3000"} {
		env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte(stdout)}, nil)
		_, err := winZoneCompareExec(t, env, "UTC")
		requireWinZoneCannotDetermine(t, err)
	}

	// Exactly one terminal _dstoff is stripped.
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("Mountain Standard Time_dstoff\r\n")}, nil)
	if value, err := winZoneCompareExec(t, env, "America/Denver"); err != nil || value != true {
		t.Fatalf("dstoff = %v, %v; want true, nil", value, err)
	}
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("Mountain Standard Time_dstoff\r\n")}, nil)
	if value, err := winZoneCompareExec(t, env, "Mountain Standard Time"); err != nil || value != true {
		t.Fatalf("dstoff windows-form request = %v, %v; want true, nil", value, err)
	}
	// Repeated suffix: only one strip happens, the remainder is
	// unlisted, and the answer is false (GAP-02).
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("Mountain Standard Time_dstoff_dstoff")}, nil)
	if value, err := winZoneCompareExec(t, env, "America/Denver"); err != nil || value != false {
		t.Fatalf("repeated dstoff = %v, %v; want false, nil", value, err)
	}

	// Lowercasing applies to the machine output (mixed case in, match out).
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("iNdIa STANDARD tImE\r\n")}, nil)
	if value, err := winZoneCompareExec(t, env, "Asia/Calcutta"); err != nil || value != true {
		t.Fatalf("mixed-case output = %v, %v; want true, nil", value, err)
	}
}

