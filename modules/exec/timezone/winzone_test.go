// pinnedSaltCommit is the salt revision this module's Windows table was
// transcribed from (references/salt.lock). Bumping the pin requires
// re-verifying the table against the new source.
const pinnedSaltCommit = "8b63e700637e40d76f80a00d95c60471797c73b9"

// repoRoot returns the repository root relative to this package's
// directory (modules/exec/timezone).
func repoRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs(filepath.Join("..", "..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	return root
}

// parsePinnedWinTimezonePairs reads the pinned Salt source and extracts
// the static TzMapper table exactly as source lines 46-183 define it:
// every `"windows": "unix",` entry in file order. Expected values come
// from the source, never from the Go table under test.
func parsePinnedWinTimezonePairs(t *testing.T) []winZonePair {
	t.Helper()
	lockData, err := os.ReadFile(filepath.Join(repoRoot(t), "references", "salt.lock"))
	if err != nil {
		t.Fatalf("read references/salt.lock: %v", err)
	}
	lock := struct {
		Commit string `yaml:"commit"`
	}{}
	// The lock is a flat three-key YAML mapping generated by
	// tools/salt-reference; parse just the commit line without pulling
	// the yaml dependency into the module test binary.
	for _, line := range strings.Split(string(lockData), "\n") {
		if strings.HasPrefix(line, "commit:") {
			lock.Commit = strings.TrimSpace(strings.TrimPrefix(line, "commit:"))
		}
	}
	if lock.Commit != pinnedSaltCommit {
		t.Fatalf("references/salt.lock commit = %q, want the pinned %q: the Windows zone table oracle must be re-verified against the new source before the table can be trusted", lock.Commit, pinnedSaltCommit)
	}
	sourcePath := filepath.Join(repoRoot(t), "saltstack", "salt", "modules", "win_timezone.py")
	data, err := os.ReadFile(sourcePath)
	if err != nil {
		t.Skipf("pinned salt submodule source unavailable (%v); source-parity oracle not run", err)
	}
	lines := strings.Split(string(data), "\n")
	start := -1
	end := -1
	for i, line := range lines {
		if start < 0 && strings.HasPrefix(line, "mapper = TzMapper(") {
			start = i + 1 // first dict line (the "{" line carries no pairs)
			continue
		}
		if start >= 0 && line == ")" {
			end = i
			break
		}
	}
	if start < 0 || end < 0 {
		t.Fatalf("could not locate the TzMapper table in %s", sourcePath)
	}
	entry := regexp.MustCompile(`^\s*"(.+)": "(.+)",$`)
	var pairs []winZonePair
	for _, line := range lines[start:end] {
		if strings.TrimSpace(line) == "{" || strings.TrimSpace(line) == "}" {
			continue
		}
		m := entry.FindStringSubmatch(line)
		if m == nil {
			t.Fatalf("unparseable TzMapper line %q in %s", line, sourcePath)
		}
		pairs = append(pairs, winZonePair{Windows: m[1], Unix: m[2]})
	}
	return pairs
}

// TestWinZoneTableMatchesPinnedSourceExactly is the WZC-03 source
// parity oracle: the Go table equals the pinned Salt source table
// pair-for-pair (count, order, both values), with expected values
// parsed from saltstack/salt/modules/win_timezone.py lines 46-183 after
// checking the references/salt.lock pin — never a checksum or any
// other value derived from the Go table under test.
func TestWinZoneTableMatchesPinnedSourceExactly(t *testing.T) {
	want := parsePinnedWinTimezonePairs(t)
	if len(want) != 134 {
		t.Fatalf("pinned source table has %d pairs, want 134", len(want))
	}
	got := winZonePairs
	if len(got) != len(want) {
		t.Fatalf("Go table has %d pairs, want %d from the pinned source", len(got), len(want))
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("pair %d = %+v, want %+v from the pinned source (count and order are part of the contract)", i, got[i], want[i])
		}
	}
}

// TestWinZoneTableInvariants pins the WZC-03 structural invariants:
// 134 pairs, no duplicate lowercase Windows keys, no duplicate Unix
// values, no duplicate lowercase Unix keys, no duplicate Windows
// values, and both derived maps round-trip every pair in both
// directions. Anchors cover the WZC-03 required evidence points:
// India/Calcutta, Mountain/Denver (the _dstoff target), FLE/Kiev (the
// no-suffix anchor), and the UTC sign mapping.
func TestWinZoneTableInvariants(t *testing.T) {
	if len(winZonePairs) != 134 {
		t.Fatalf("table has %d pairs, want 134", len(winZonePairs))
	}
	if len(winZoneToUnix) != 134 {
		t.Fatalf("windows->unix map has %d entries, want 134 (duplicate lowercase keys would collapse)", len(winZoneToUnix))
	}
	if len(unixZoneToWin) != 134 {
		t.Fatalf("unix->windows map has %d entries, want 134 (duplicate lowercase keys would collapse)", len(unixZoneToWin))
	}
	seenWindows, seenUnix := map[string]bool{}, map[string]bool{}
	for _, pair := range winZonePairs {
		if seenWindows[pair.Windows] {
			t.Fatalf("duplicate Windows name %q", pair.Windows)
		}
		seenWindows[pair.Windows] = true
		if seenUnix[pair.Unix] {
			t.Fatalf("duplicate Unix name %q", pair.Unix)
		}
		seenUnix[pair.Unix] = true
		if winZoneToUnix[strings.ToLower(pair.Windows)] != pair.Unix {
			t.Fatalf("windows->unix round-trip broken for %+v", pair)
		}
		if unixZoneToWin[strings.ToLower(pair.Unix)] != pair.Windows {
			t.Fatalf("unix->windows round-trip broken for %+v", pair)
		}
	}
	anchors := []winZonePair{
		{"India Standard Time", "Asia/Calcutta"},
		{"Mountain Standard Time", "America/Denver"},
		{"FLE Standard Time", "Europe/Kiev"},
		{"UTC", "Etc/GMT"},
		{"UTC+12", "Etc/GMT-12"},
		{"UTC+13", "Etc/GMT-13"},
		{"UTC-02", "Etc/GMT+2"},
		{"Dateline Standard Time", "Etc/GMT+12"},
	}
	for _, anchor := range anchors {
		if winZoneToUnix[strings.ToLower(anchor.Windows)] != anchor.Unix {
			t.Fatalf("anchor %+v missing or wrong", anchor)
		}
	}
}

// TestWinZoneCompareRegistrationContract pins the WZC-15/WZC-16
// registration shape of the windows variant: the canonical loader name
// timezone.zone_compare, the [windows] platform constraint, and the
// catalog-declared args schema — exactly one required string timezone
// field (win_timezone.yaml zone_compare(timezone), no default), with
// the canonical argument name proven by the missing-required gate
// error.
func TestWinZoneCompareRegistrationContract(t *testing.T) {
	var fn runtime.ExecFunction = winZoneCompareFunc{}
	if fn.Name() != "timezone.zone_compare" {
		t.Fatalf("name = %q, want timezone.zone_compare", fn.Name())
	}
	constrained, ok := fn.(runtime.PlatformConstrained)
	if !ok {
		t.Fatal("winZoneCompareFunc must be platform-constrained")
	}
	if !reflect.DeepEqual(constrained.Platforms(), []string{"windows"}) {
		t.Fatalf("platforms = %v, want [windows]", constrained.Platforms())
	}
	if !runtime.SupportsPlatform(fn, "windows") {
		t.Fatal("windows zone_compare must support windows")
	}
	for _, goos := range []string{"linux", "darwin", "freebsd", "solaris", "aix"} {
		if runtime.SupportsPlatform(fn, goos) {
			t.Fatalf("windows zone_compare must not support %s", goos)
		}
	}
	argsType := reflect.TypeOf(fn.Args())
	if argsType.Kind() != reflect.Struct || argsType.NumField() != 1 {
		t.Fatalf("args type = %s with %d fields, want a one-field struct", argsType, argsType.NumField())
	}
	field := argsType.Field(0)
	if field.Name != "TimeZone" || field.Type.Kind() != reflect.Pointer || field.Type.Elem().Kind() != reflect.String ||
		field.Tag.Get("statekit") != "required,name=timezone" {
		t.Fatalf("timezone field = %s %s tag %q, want *string TimeZone tagged required,name=timezone (WZC-BACKEND-01: missing must differ from explicit empty)", field.Name, field.Type, field.Tag.Get("statekit"))
	}
	if err := config.ValidateRequired(&winZoneCompareArgs{}); err == nil || err.Error() != `missing required argument "timezone"` {
		t.Fatalf("missing timezone err = %v, want missing required argument \"timezone\"", err)
	}
}

// TestWinZoneSentinels pins the WZC-12 sentinel basis: exactly two
// distinct fixed execution-category sentinels with exact value-free
// texts, no cross-match through errors.Is, and no Unwrap reachability.
func TestWinZoneSentinels(t *testing.T) {
	if ErrInvalidWindowsZone.Error() != "invalid Windows timezone" {
		t.Fatalf("ErrInvalidWindowsZone text = %q", ErrInvalidWindowsZone.Error())
	}
	if ErrCannotDetermineZone.Error() != "cannot determine current zone" {
		t.Fatalf("ErrCannotDetermineZone text = %q", ErrCannotDetermineZone.Error())
	}
	if errors.Is(ErrInvalidWindowsZone, ErrCannotDetermineZone) {
		t.Fatal("ErrInvalidWindowsZone must never match ErrCannotDetermineZone")
	}
	if errors.Is(ErrCannotDetermineZone, ErrInvalidWindowsZone) {
		t.Fatal("ErrCannotDetermineZone must never match ErrInvalidWindowsZone")
	}
	if errors.Unwrap(ErrInvalidWindowsZone) != nil || errors.Unwrap(ErrCannotDetermineZone) != nil {
		t.Fatal("sentinels must not wrap a raw cause")
	}
	if ErrInvalidWindowsZone == ErrCannotDetermineZone {
		t.Fatal("sentinels must be distinct values")
	}
}

// TestValidateWindowsSystemTree pins the WZC-08 matrix: both API
// answers must be absolute, lexically clean local drive paths, and the
// system directory must be the exact case-insensitive System32/SysWOW64
// immediate child of the machine-wide windows directory. UNC, device,
// extended-length, drive-relative, root-relative, relative, traversal,
// sibling, deeper, ADS, control-character, forward-slash, and
// empty-component answers are rejected, as is any malformed windows
// directory even beside a well-formed system directory.
func TestValidateWindowsSystemTree(t *testing.T) {
	valid := []struct {
		label          string
		sysdir, windir string
	}{
		{"classic System32", `C:\Windows\System32`, `C:\Windows`},
		{"case-insensitive", `C:\WINDOWS\system32`, `C:\Windows`},
		{"SysWOW64", `C:\Windows\SysWOW64`, `C:\WINDOWS`},
		{"non-C drive", `D:\Win\System32`, `D:\Win`},
		{"spaces in tree", `C:\Wi ndows\System32`, `C:\Wi ndows`},
		{"non-ascii tree", `C:\Wīndows\System32`, `C:\Wīndows`},
	}
	for _, tc := range valid {
		if !validateWindowsSystemTree(tc.sysdir, tc.windir) {
			t.Fatalf("%s: validate(%q, %q) = false, want true", tc.label, tc.sysdir, tc.windir)
		}
	}
	const windir = `C:\Windows`
	invalid := []struct {
		label          string
		sysdir, winDir string
	}{
		{"empty both", "", ""},
		{"empty sysdir", "", windir},
		{"empty windir", `C:\Windows\System32`, ""},
		{"unc paths", `\\server\share\System32`, `\\server\share`},
		{"extended-length sysdir", `\\?\C:\Windows\System32`, windir},
		{"device sysdir", `\\.\C:\Windows\System32`, windir},
		{"drive-relative sysdir", `C:Windows\System32`, `C:Windows`},
		{"drive-relative beside clean windir", `C:Windows\System32`, windir},
		{"root-relative", `\Windows\System32`, `\Windows`},
		{"relative", `Windows\System32`, `Windows`},
		{"traversal inside", `C:\Windows\..\System32`, windir},
		{"traversal final", `C:\Windows\System32\..`, windir},
		{"sibling tree", `C:\Other\System32`, windir},
		{"sibling child name", `C:\Windows\System31`, windir},
		{"deeper below System32", `C:\Windows\System32\Drivers`, windir},
		{"deeper nested System32", `C:\Windows\Foo\System32`, windir},
		{"ADS on sysdir", `C:\Windows\System32:hidden`, windir},
		{"control char in sysdir", "C:\\Windows\\System3\x02", windir},
		{"NUL in windir", `C:\Windows\System32`, "C:\\Wind\x00ows"},
		{"forward slash sysdir", `C:/Windows/System32`, windir},
		{"forward slash windir", `C:\Windows\System32`, `C:/Windows`},
		{"trailing separator", `C:\Windows\System32\`, windir},
		{"double separator sysdir", `C:\Windows\\System32`, windir},
		{"double separator windir", `C:\Windows\System32`, `C:\\Windows`},
		{"dot component", `C:\Windows\.\System32`, windir},
		{"dot windir", `C:\Windows\System32`, `C:\Windows\.`},
		{"volume-root windir", `C:\System32`, `C:\`},
		{"short sysdir", `C:\`, windir},
		{"no drive", `:\Windows\System32`, `:\Windows`},
		{"digit drive", `1:\Windows\System32`, `1:\Windows`},
		{"malformed windir extended", `C:\Windows\System32`, `\\?\C:\Windows`},
		{"malformed windir drive-relative", `C:\Windows\System32`, `C:Windows`},
	}
	for _, tc := range invalid {
		if validateWindowsSystemTree(tc.sysdir, tc.winDir) {
			t.Fatalf("%s: validate(%q, %q) = true, want false", tc.label, tc.sysdir, tc.winDir)
		}
	}
}

// TestWinZoneResolverSeamFailsClosedOffWindows pins the !windows stub:
// the default resolver answers an error off windows so a windows
// variant that somehow executes on the wrong host fails closed with
// ErrCannotDetermineZone rather than probing the host. On windows the
// default resolver is the real API pair and is never exercised by this
// hermetic suite.
func TestWinZoneResolverSeamFailsClosedOffWindows(t *testing.T) {
	if runtime.CurrentGOOS() == "windows" {
		t.Skip("default resolver is the real windows API pair; hermetic suite never calls it on windows")
	}
	sysdir, windir, err := defaultWinSystemTree()
	if err == nil {
		t.Fatal("defaultWinSystemTree off windows must fail closed")
	}
	if sysdir != "" || windir != "" {
		t.Fatalf("defaultWinSystemTree off windows = (%q, %q), want empty values", sysdir, windir)
	}
	// The seam is assignable so hermetic tests can fake the OS path API.
	restore := winSystemTree
	defer func() { winSystemTree = restore }()
	winSystemTree = func() (string, string, error) { return `C:\Windows\System32`, `C:\Windows`, nil }
	if s, w, err := winSystemTree(); err != nil || s != `C:\Windows\System32` || w != `C:\Windows` {
		t.Fatalf("seam override = (%q, %q, %v)", s, w, err)
	}
}

// winZoneRunner is the fake Runner for the windows zone_compare
// contract: it deep-records every process.Command and replays scripted
// results, and it surfaces context cancellation when the caller's
// context is already dead.
type winZoneRunner struct {
	replies []process.CommandResult
	cmds    []process.Command
}

func (r *winZoneRunner) Run(ctx context.Context, cmd process.Command) process.CommandResult {
	r.cmds = append(r.cmds, cmd)
	if ctx.Err() != nil {
		return process.CommandResult{ExitCode: -1, Err: fmt.Errorf("tzutil canceled: %w", ctx.Err())}
	}
	if len(r.replies) == 0 {
		return process.CommandResult{ExitCode: 0}
	}
	next := r.replies[0]
	r.replies = r.replies[1:]
	return next
}

// winZoneResolver is the fake OS path API for the system-tree seam.
type winZoneResolver struct {
	sysdir, windir string
	err            error
	calls          int
}

// overrideWinSystemTree replaces the resolver seam for one test and
// restores it afterwards.
func overrideWinSystemTree(t *testing.T, sysdir, windir string, err error) *winZoneResolver {
	t.Helper()
	fake := &winZoneResolver{sysdir: sysdir, windir: windir, err: err}
	previous := winSystemTree
	winSystemTree = func() (string, string, error) {
		fake.calls++
		return fake.sysdir, fake.windir, fake.err
	}
	t.Cleanup(func() { winSystemTree = previous })
	return fake
}

const (
	winZoneTestSysdir = `C:\Windows\System32`
	winZoneTestWindir = `C:\Windows`
	winZoneTestExe    = winZoneTestSysdir + `\tzutil.exe`
)

// winZoneEnv is one hermetic windows-variant environment: fake
// resolver, fixture MemoryFS wrapped in the write-rejecting recording
// FS, and the fake Runner with one scripted reply.
type winZoneEnv struct {
	rt       *runtime.Runtime
	runner   *winZoneRunner
	fsys     *zoneRecordingFS
	resolver *winZoneResolver
}

// newWinZoneEnv builds the default environment — resolver answering
// C:\Windows\System32 under C:\Windows and a regular tzutil.exe — and
// lets mutate seed extra fixtures or override Lstat modes at the exe
// path (nil keeps the regular exe).
func newWinZoneEnv(t *testing.T, reply process.CommandResult, mutate func(mem runtime.FileSystem, rec *zoneRecordingFS)) *winZoneEnv {
	t.Helper()
	resolver := overrideWinSystemTree(t, winZoneTestSysdir, winZoneTestWindir, nil)
	mem := runtime.NewMemoryFS()
	rec := &zoneRecordingFS{FileSystem: mem, lstatMode: map[string]fs.FileMode{}}
	if mutate == nil {
		zoneMustWrite(mem, winZoneTestExe, []byte("MZ fake tzutil"))
	} else {
		mutate(mem, rec)
	}
	runner := &winZoneRunner{replies: []process.CommandResult{reply}}
	rt := &runtime.Runtime{Facts: facts.ForTesting(facts.Overrides{}), FS: rec, Runner: runner}
	return &winZoneEnv{rt: rt, runner: runner, fsys: rec, resolver: resolver}
}

