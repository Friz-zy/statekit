// WZC-13 (GAP-07): nonzero exit, Runner error, cancellation, deadline,
// zero-exit truncation on either stream, and over-cap captures each
// fail closed with only ErrCannotDetermineZone — never the parsed
// value and never the invalid-zone sentinel; the stdout cap boundary
// is exact at 64 KiB.
func TestWinZoneCompareFailureModes(t *testing.T) {
	valid := []byte("India Standard Time\r\n")
	env := newWinZoneEnv(t, process.CommandResult{ExitCode: 1, Stdout: valid}, nil)
	_, err := winZoneCompareExec(t, env, "Asia/Calcutta")
	requireWinZoneCannotDetermine(t, err)

	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: valid, Err: errors.New(`fork/exec C:\Windows\System32\tzutil.exe: Access is denied`)}, nil)
	_, err = winZoneCompareExec(t, env, "Asia/Calcutta")
	requireWinZoneCannotDetermine(t, err)
	if strings.Contains(err.Error(), "Access") || strings.Contains(err.Error(), "tzutil") || strings.Contains(err.Error(), "Windows") {
		t.Fatalf("runner error text %q leaks the raw cause", err.Error())
	}

	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: valid, Err: fmt.Errorf("tzutil: %w", context.Canceled)}, nil)
	_, err = winZoneCompareExec(t, env, "Asia/Calcutta")
	requireWinZoneCannotDetermine(t, err)

	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: valid, Err: fmt.Errorf("tzutil: %w", context.DeadlineExceeded)}, nil)
	_, err = winZoneCompareExec(t, env, "Asia/Calcutta")
	requireWinZoneCannotDetermine(t, err)

	// A caller context that is already dead surfaces through the
	// Runner result as the same fixed error.
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: valid}, nil)
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	zoneArg := "Asia/Calcutta"
	_, err = (winZoneCompareFunc{}).Execute(ctx, env.rt, &winZoneCompareArgs{TimeZone: &zoneArg})
	requireWinZoneCannotDetermine(t, err)

	// Zero-exit truncation on either stream fails closed even with an
	// otherwise valid stdout.
	for _, tc := range []struct {
		label string
		reply process.CommandResult
	}{
		{"stdout truncated", process.CommandResult{ExitCode: 0, Stdout: valid, StdoutTruncated: true}},
		{"stderr truncated", process.CommandResult{ExitCode: 0, Stdout: valid, StderrTruncated: true}},
	} {
		env := newWinZoneEnv(t, tc.reply, nil)
		_, err := winZoneCompareExec(t, env, "Asia/Calcutta")
		if errors.Is(err, ErrInvalidWindowsZone) {
			t.Fatalf("%s: err must never be the invalid-zone sentinel", tc.label)
		}
		requireWinZoneCannotDetermine(t, err)
	}

	// Exact cap boundary: 65536 stdout bytes are accepted when the
	// rstripped content is a valid zone (the zone plus trailing
	// whitespace inside the budget); 65537 are rejected. Stderr at
	// 65537 is rejected too.
	pad := func(total int) []byte {
		p := bytes.Repeat([]byte(" "), total)
		copy(p, "UTC\r\n")
		return p
	}
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: pad(64 << 10)}, nil)
	if value, err := winZoneCompareExec(t, env, "UTC"); err != nil || value != true {
		t.Fatalf("65536-byte stdout = %v, %v; want true, nil", value, err)
	}
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: pad(64<<10 + 1)}, nil)
	_, err = winZoneCompareExec(t, env, "UTC")
	requireWinZoneCannotDetermine(t, err)
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: valid, Stderr: bytes.Repeat([]byte("e"), 64<<10+1)}, nil)
	_, err = winZoneCompareExec(t, env, "Asia/Calcutta")
	requireWinZoneCannotDetermine(t, err)
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: valid, Stderr: bytes.Repeat([]byte("e"), 64<<10)}, nil)
	if value, err := winZoneCompareExec(t, env, "Asia/Calcutta"); err != nil || value != true {
		t.Fatalf("65536-byte stderr = %v, %v; want true, nil", value, err)
	}
}

