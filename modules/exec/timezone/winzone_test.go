// WZC-BACKEND-01: the required *string timezone argument makes a
// missing argument distinguishable from an explicit empty string. The
// registry/config boundary (a missing key) fails the required-Args
// gate with the decoder's fixed missing-required error before the
// function — and therefore before any resolver, Lstat, or dispatch —
// can run; an explicit nonnil pointer to "" passes that gate and
// Execute's own name gate then answers the fixed invalid-zone
// sentinel with the same zero-work guarantee and no cross-match to the
// execution sentinel; a valid pointer proceeds exactly as before.
func TestWinZoneCompareRequiredGateBoundary(t *testing.T) {
	env := newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("UTC\r\n")}, nil)

	// Registry/config boundary: the zero prototype (missing timezone
	// key -> nil pointer) fails required validation with the fixed
	// value-free missing-required error.
	var missing *config.MissingRequiredError
	err := config.ValidateRequired(&winZoneCompareArgs{})
	if !errors.As(err, &missing) || missing.Name != "timezone" {
		t.Fatalf("missing timezone err = %v, want config.MissingRequiredError timezone", err)
	}
	if err.Error() != `missing required argument "timezone"` {
		t.Fatalf("missing timezone err text = %q", err.Error())
	}

	// Direct Execute with a nonnil struct but nil pointer reuses the
	// decoder's fixed missing-required error (registry gate parity),
	// never a panic and never any work.
	value, execErr := (winZoneCompareFunc{}).Execute(context.Background(), env.rt, &winZoneCompareArgs{})
	if value != nil {
		t.Fatalf("nil-pointer timezone value = %#v, want nil", value)
	}
	if !errors.As(execErr, &missing) || missing.Name != "timezone" {
		t.Fatalf("nil-pointer timezone err = %v, want config.MissingRequiredError timezone", execErr)
	}
	if env.resolver.calls != 0 || len(env.runner.cmds) != 0 || len(env.fsys.calls) != 0 {
		t.Fatalf("nil-pointer timezone did work: resolver=%d dispatch=%d fs=%v", env.resolver.calls, len(env.runner.cmds), env.fsys.calls)
	}

	// Explicit empty pointer: required validation passes (the pointer
	// is set), and Execute answers only the invalid-zone sentinel.
	empty := ""
	if err := config.ValidateRequired(&winZoneCompareArgs{TimeZone: &empty}); err != nil {
		t.Fatalf("explicit empty pointer must pass required validation, got %v", err)
	}
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("UTC\r\n")}, nil)
	value, execErr = (winZoneCompareFunc{}).Execute(context.Background(), env.rt, &winZoneCompareArgs{TimeZone: &empty})
	if value != nil {
		t.Fatalf("explicit empty value = %#v, want nil", value)
	}
	requireWinZoneInvalid(t, execErr)
	if env.resolver.calls != 0 || len(env.runner.cmds) != 0 || len(env.fsys.calls) != 0 {
		t.Fatalf("explicit empty did work: resolver=%d dispatch=%d fs=%v", env.resolver.calls, len(env.runner.cmds), env.fsys.calls)
	}

	// Valid pointer contrast: the gate passes and exactly one dispatch
	// runs — behavior unchanged from the pre-pointer contract.
	env = newWinZoneEnv(t, process.CommandResult{ExitCode: 0, Stdout: []byte("India Standard Time\r\n")}, nil)
	zone := "Asia/Calcutta"
	value, execErr = (winZoneCompareFunc{}).Execute(context.Background(), env.rt, &winZoneCompareArgs{TimeZone: &zone})
	if execErr != nil || value != true {
		t.Fatalf("valid pointer = %v, %v; want true, nil", value, execErr)
	}
	if len(env.runner.cmds) != 1 {
		t.Fatalf("valid pointer dispatched %d commands, want 1", len(env.runner.cmds))
	}
}
